def unescape(s):
    return s.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')

def enc(s):
    # s: 实际字符串（可能含真实换行）。写成 PO 多行引号形式。
    s = s.replace('\\', '\\\\').replace('"', '\\"')
    parts = s.split('\n')
    return '\n'.join('"' + p + '"' for p in parts)

